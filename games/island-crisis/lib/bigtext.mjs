export const bigWidth = (text, px) => Math.max(0, String(text).length * 6 * px - px);

export function bigWrite(api, text, x, y, px, col, shadow = null) {
  if (shadow) bigWrite(api, text, x + px * .5, y + px * .5, px, shadow);
  let cx = x;
  for (const ch of String(text).toLowerCase()) {
    const g = G[ch];
    if (g) for (let r = 0; r < 7; r++) {
      let c = 0;
      while (c < 5) {
        if (g[r * 5 + c] !== '1') { c++; continue; }
        let e = c;
        while (e < 5 && g[r * 5 + e] === '1') e++;
        api.box(cx + c * px, y + r * px, (e - c) * px, px, ...col);
        c = e;
      }
    }
    cx += 6 * px;
  }
}

export function bigCentered(api, text, cx, y, px, col, shadow = [16, 18, 30]) {
  bigWrite(api, text, cx - bigWidth(text, px) / 2, y, px, col, shadow);
}
