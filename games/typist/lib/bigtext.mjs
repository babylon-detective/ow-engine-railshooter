export const glyphWidth = (cell) => cell * 6;   // five columns and a gap
export function drawGlyph(api, ch, x, y, cell, r, g, b) {
  const rows = (G[ch] || "").split(" ");
  rows.forEach((row, j) => { for (let i = 0; i < 5; i++) if (row[i] === "1") api.box(x + i * cell, y + j * cell, cell + .5, cell + .5, r, g, b); });
}
